import Foundation

/// Подсети, которые обязаны остаться в туннеле при укрупнении списка.
///
/// Российская зона — это тысячи подсетей, и передавать их системе по одной
/// дорого: туннель поднимается долго. Список укрупняется, но при этом в
/// прямой канал могут случайно попасть соседние чужие адреса. Вот эти —
/// не должны: на них живут сервисы, ради которых VPN и включают.
enum KeepInTunnel {

    private static let texts = [
        "185.199.108.0/22",   // GitHub Pages
        "194.55.24.0/21",     // Deutsche Welle
        "195.8.208.0/20",     // Dailymotion
        "192.147.128.0/18",   // Adobe
        "192.178.0.0/15",     // Google, AI Studio
        "199.36.153.0/24",    // Firebase
        "151.101.0.0/16",     // Fastly
        "146.75.0.0/16",      // Fastly
        "199.232.0.0/16",     // Fastly
    ]

    static func nets() -> [Ipv4Net] { texts.compactMap { Cidr.parse($0) } }
}
