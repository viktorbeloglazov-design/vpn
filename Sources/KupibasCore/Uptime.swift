import Foundation

/// Сколько служба на самом деле работала — без времени, проведённого во сне.
///
/// Разобрано по записям о перезапусках с Mac. Сторож живости должен был
/// срабатывать через полторы минуты, а срабатывал через пятнадцать:
///
///     встала на «wg show utun4 dump» на 962 с
///     встала на «проверяю, проходят ли большие порции» на 1046 с
///     встала на «networksetup -getinfo …» на 919 с
///
/// Ни одна из этих команд столько не идёт. Просто компьютер закрыли:
/// поток сторожа во сне не исполняется, а обычные часы идут. Проснувшись,
/// сторож видел «служба молчит шестнадцать минут» и перезапускал её —
/// хотя она спала вместе с компьютером и была цела.
///
/// Так и выглядело «служба отпадает через время»: каждый сон ноутбука
/// стоил перезапуска, а с ним — опускания туннеля и всего круга подъёма
/// заново.
///
/// Поэтому время для сторожа считается этими часами: они идут, только
/// пока машина не спит. Разница между ними и обычными часами и есть
/// длительность сна.
public enum Uptime {

    /// Секунды с запуска системы, не считая сна.
    public static func seconds() -> TimeInterval {
        var now = timespec()
        // CLOCK_UPTIME_RAW — единственные часы на этой системе, которые
        // во сне стоят. CLOCK_MONOTONIC здесь продолжает идти.
        guard clock_gettime(CLOCK_UPTIME_RAW, &now) == 0 else {
            // Часы не ответили — других нет. Обычные лучше, чем ничего:
            // сторож станет чувствительнее ко сну, но не ослепнет.
            return Date().timeIntervalSince1970
        }
        return TimeInterval(now.tv_sec) + TimeInterval(now.tv_nsec) / 1_000_000_000
    }
}
