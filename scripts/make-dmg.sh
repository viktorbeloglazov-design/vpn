#!/bin/bash
# Пакует собранное приложение в образ для скачивания.
#
#   scripts/make-dmg.sh 1.0.0 [--app dist/QPVPN.app] [--out dist]
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
VERSION="${1:?укажите версию, например 1.0.0}"
shift || true

APP="$ROOT/dist/QPVPN.app"
OUT_DIR="$ROOT/dist"

while [ $# -gt 0 ]; do
    case "$1" in
        --app) APP="$2"; shift 2 ;;
        --out) OUT_DIR="$2"; shift 2 ;;
        *) echo "Неизвестный аргумент: $1" >&2; exit 1 ;;
    esac
done

if [ ! -d "$APP" ]; then
    echo "Не найдено приложение: $APP" >&2
    exit 1
fi

STAGE="$(mktemp -d)"
trap 'rm -rf "$STAGE"' EXIT

cp -R "$APP" "$STAGE/QPVPN.app"
ln -s /Applications "$STAGE/Applications"

# Программа удаления едет в том же образе. Она нужна ровно тогда, когда
# копий накопилось несколько и запускается не та — скачивать что-то
# отдельно в этот момент человеку особенно некстати.
UNINSTALLER="$ROOT/dist/Удалить QP VPN.app"
if [ -d "$UNINSTALLER" ]; then
    cp -R "$UNINSTALLER" "$STAGE/Удалить QP VPN.app"
fi

cat > "$STAGE/ЧИТАТЬ ПЕРВЫМ.txt" <<'TXT'
QP VPN — установка

1. Перетащите QPVPN.app в папку Applications (ярлык рядом).

2. ПЕРВЫЙ ЗАПУСК. macOS покажет окно «Файл "QPVPN" не был открыт»
   — это обычная защита от программ без сертификата Apple. Обойти её
   нужно один раз, любым из двух способов:

     • нажмите «Готово» в этом окне (НЕ «Переместить в Корзину»);
     • меню Apple → Системные настройки;
     • Конфиденциальность и безопасность;
     • пролистайте вниз до строки про QPVPN;
     • нажмите «Открыть всё равно», подтвердите паролем или Touch ID;
     • в следующем окне ещё раз «Открыть».

3. В окне приложения появится жёлтая полоса «Служба не установлена» —
   нажмите «Установить службу» и введите пароль администратора.
   Терминал для этого не нужен.

4. Вкладка «Сервер» → «Вставить конфиг WireGuard…» → вставьте конфиг
   вашего сервера в Казахстане → «Импортировать».

5. Нажмите круглую кнопку включения и проверьте «Проверить мой IP».


ЕСЛИ ОТКРЫВАЕТСЯ СТАРАЯ ВЕРСИЯ

Откройте «Удалить QP VPN» — она здесь же, в этом образе. Программа
покажет все копии, которые есть на компьютере: где лежат, какой версии
и какая из них сейчас работает. Нажмите «Убрать лишние копии» — ключ
и настройки при этом останутся.

Так бывает, потому что программа живёт в строке меню и не закрывается
вместе с окном. Пока старая копия в памяти, система показывает именно
её, сколько новых ни поставь.

Если жёлтая полоса не исчезла, журнал службы: /var/log/kupibas-vpn.log

Все утилиты WireGuard уже внутри приложения — ставить ничего больше не нужно.
TXT

DMG="$OUT_DIR/QPVPN-$VERSION.dmg"
mkdir -p "$OUT_DIR"
rm -f "$DMG"

hdiutil create \
    -volname "QP VPN" \
    -srcfolder "$STAGE" \
    -ov -format UDZO \
    "$DMG" >/dev/null

echo "Готово: $DMG"
