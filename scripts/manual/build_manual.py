TOTAL = 10


def qr(text):
    """QR-код в виде встроенного SVG — печатается без обращения к сети."""
    buf = io.BytesIO()
    segno.make(text, error="m").save(buf, kind="svg", omitsize=True, border=2,
                                     dark="#0A1015", svgclass=None, xmldecl=False)
    return buf.getvalue().decode("utf-8")


def logo():
    data = (ROOT / "windows/app/Assets/logo-dark.png").read_bytes()
    return "data:image/png;base64," + base64.b64encode(data).decode()


