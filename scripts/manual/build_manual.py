def link(url, text, plain=False):
    """Слово со ссылкой.

    В PDF такие слова кликаются: инструкцию читают с экрана или с телефона,
    и набирать длинный адрес руками никто не станет.
    """
    return f'<a class="{"plain" if plain else "lnk"}" href="{url}">{text}</a>'


