package kz.qpvpn.model

/**
 * Подсети, которые обязаны остаться в туннеле.
 *
 * Список России приходится укрупнять: точный вариант даёт больше двадцати
 * тысяч маршрутов, а столько Android принять не может. При укрупнении мимо
 * туннеля уходят и соседние чужие блоки — обычно это европейские
 * провайдеры, но иногда в них живут нужные сервисы.
 *
 * Здесь перечислено то, что проверено и не должно уходить напрямую:
 * блоки вычитаются из списка обхода перед расчётом маршрутов.
 */
object KeepInTunnel {

    val prefixes: List<String> = listOf(
        "185.199.108.0/22",   // страницы GitHub
        "194.55.24.0/21",     // Deutsche Welle
        "195.8.208.0/20",     // Dailymotion
        "192.147.128.0/18",   // вход Adobe
        "192.178.0.0/15",     // сервисы Google, включая AI Studio
        "199.36.153.0/24",    // Firebase Hosting
        "151.101.0.0/16",     // Fastly: на нём живут многие сервисы
        "146.75.0.0/16",      // Fastly
        "199.232.0.0/16",     // Fastly
    )

    fun nets(): List<kz.qpvpn.net.Ipv4Net> = prefixes.mapNotNull { kz.qpvpn.net.Cidr.parse(it) }
}
