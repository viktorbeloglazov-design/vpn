import Foundation

/// Счётчик осечек подряд: отличает случайную от настоящей поломки.
///
/// Служба спрашивает у `wg`, как дела у туннеля. Одна неудачная попытка
/// ещё ничего не значит: система бывает занята, утилита не успевает
/// ответить за отведённое время. Но раньше служба на первой же осечке
/// считала туннель упавшим и пересоздавала его целиком — снимала тысячи
/// маршрутов, возвращала DNS, поднимала всё заново и заново подбирала
/// размер пакета. Это минута без связи, и всё из-за одного пропущенного
/// ответа.
///
/// Поэтому считаем осечки подряд. Настоящая поломка не проходит сама,
/// и её видно по второй и третьей попытке; случайная пропадает.
public struct FaultStreak: Equatable {

    /// Сколько осечек подряд терпим.
    public let limit: Int

    private var count = 0

    public init(limit: Int = 3) {
        self.limit = max(1, limit)
    }

    /// Сколько осечек подряд сейчас.
    public var current: Int { count }

    /// Попытка не удалась. Вернёт true, когда пора чинить по-настоящему.
    @discardableResult
    public mutating func miss() -> Bool {
        count += 1
        if count >= limit {
            count = 0
            return true
        }
        return false
    }

    /// Попытка удалась — счёт обнуляется.
    public mutating func hit() {
        count = 0
    }
}
